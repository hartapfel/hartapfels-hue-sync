'use strict';
var assert = require('assert');
var EventEmitter = require('events').EventEmitter;
var PassThrough = require('stream').PassThrough;
var register = require('../capture-service/capture');
var captureFeed = require('../service/capture-feed');
var handlers = {}, child, permitted = true, launched = 0, killed = 0;
register({register:function (id, request, cancel) {
    handlers[id] = {request:request, cancel:cancel};
}}, function (done) { done(permitted); }, function () {
    ++launched;
    child = new EventEmitter();
    child.kill = function () { ++killed; };
    child.stdio = [null,null,null,new PassThrough()];
    return child;
});
var trusted = 'org.webosbrew.c9screensync.service';
function message(sender, subscription, token) {
    var m = {sender:sender,isSubscription:subscription,uniqueToken:token,replies:[]};
    m.respond = function (r) { m.replies.push(r); return true; };
    m.cancel = function (r) { handlers.frames.cancel(m); m.respond(r); };
    return m;
}
var other = message('another.app',true,'other');
handlers.frames.request(other);
assert.strictEqual(other.replies[0].returnValue,false);
var denied = message(trusted,true,'denied');
permitted = false;
handlers.frames.request(denied);
assert.strictEqual(denied.replies[0].errorCode,77);
assert.strictEqual(launched,0);
permitted = true;
var m = message(trusted,true,'session');
handlers.frames.request(m);
var busy = message(trusted,true,'busy');
handlers.frames.request(busy);
assert.strictEqual(busy.replies[0].returnValue,false);
assert.strictEqual(killed,0);
var frame = new Buffer(84);
for (var i=0;i<84;i++) frame[i]=i;
child.stdio[3].write(frame.slice(0,55));
assert.strictEqual(m.replies.length,0);
child.stdio[3].write(frame.slice(55));
assert.strictEqual(m.replies[0].zones,frame.toString('base64'));
handlers.frames.cancel(other);
assert.strictEqual(killed,0);
handlers.frames.cancel(m);
assert.strictEqual(killed,1);
child.emit('close',0);
var sub = new EventEmitter(), pipe = new EventEmitter(), writes = [], errors = [];
sub.cancel = function () { sub.emit('cancel'); };
pipe.end = function () {};
pipe.write = function (buf) { writes.push(buf); return false; };
var feed = captureFeed({subscribe:function () {return sub;}});
var cancel = feed.stream(pipe,function (err) {errors.push(err);});
sub.emit('response',{payload:m.replies[0]});
sub.emit('response',{payload:m.replies[0]});
assert.strictEqual(writes.length,1);
assert.strictEqual(writes[0].toString('hex'),frame.toString('hex'));
pipe.emit('drain');
sub.emit('response',{payload:m.replies[0]});
assert.strictEqual(writes.length,2);
cancel();
sub.emit('response',{payload:m.replies[0]});
assert.strictEqual(writes.length,2);
assert.strictEqual(errors.length,0);
console.log('Capture caller checks, partial frames, backpressure and cancellation passed on '+process.version);
